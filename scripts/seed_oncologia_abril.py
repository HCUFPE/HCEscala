def seed_oncologia_abril_sync(cursor):
    """
    Executa a sincronização sincrona da UORG Oncologia (Ambulatório) e insere as grades de Abril de 2026.
    """
    print("Iniciando seed Oncologia (Ambulatório) para Abril/2026...")

    # 1. Localizar ou Criar UORG 'UNIDADE DE AMBULATÓRIO'
    cursor.execute("SELECT id FROM uorgs WHERE UPPER(nome) LIKE '%AMBULAT%' OR UPPER(sigla) = 'AMB'")
    amb_row = cursor.fetchone()
    if amb_row:
        amb_id = amb_row[0]
    else:
        cursor.execute("""
            INSERT INTO uorgs (nome, sigla, login, data_alteracao)
            VALUES ('UNIDADE DE AMBULATÓRIO', 'AMB', 'sistema', datetime('now'))
        """)
        amb_id = cursor.lastrowid
        print(f"UORG 'UNIDADE DE AMBULATÓRIO' criada (ID: {amb_id})")

    # 2. Localizar ou Criar UORG subordinada 'ONCOLOGIA'
    cursor.execute("SELECT id FROM uorgs WHERE UPPER(nome) = 'ONCOLOGIA'")
    onco_row = cursor.fetchone()
    if onco_row:
        onco_id = onco_row[0]
        cursor.execute("UPDATE uorgs SET uorg_pai_id = ? WHERE id = ? AND (uorg_pai_id IS NULL OR uorg_pai_id = '')", (amb_id, onco_id))
    else:
        cursor.execute("""
            INSERT INTO uorgs (nome, sigla, uorg_pai_id, login, data_alteracao)
            VALUES ('ONCOLOGIA', 'ONCO', ?, 'sistema', datetime('now'))
        """, (amb_id,))
        onco_id = cursor.lastrowid
        print(f"UORG 'ONCOLOGIA' criada (ID: {onco_id})")

    # 3. Localizar ou Criar Posto de Serviço 'ONCOLOGIA'
    cursor.execute("SELECT id FROM postos WHERE UPPER(nome) = 'ONCOLOGIA' AND (uorg_id = ? OR unidade_id = ?)", (onco_id, onco_id))
    posto_row = cursor.fetchone()
    if posto_row:
        posto_onco_id = posto_row[0]
    else:
        cursor.execute("""
            INSERT INTO postos (nome, uorg_id, unidade_id, login, data_alteracao)
            VALUES ('ONCOLOGIA', ?, ?, 'sistema', datetime('now'))
        """, (onco_id, onco_id))
        posto_onco_id = cursor.lastrowid
        print(f"Posto de Serviço 'ONCOLOGIA' criado (ID: {posto_onco_id})")

    # 4. Mapeamento de Vínculos (CLT, RJU, EBSERH)
    cursor.execute("SELECT id, UPPER(nome) FROM vinculos")
    vinculos_map = {row[1]: row[0] for row in cursor.fetchall()}
    
    # Garantir vínculos CLT e RJU
    if "CLT" not in vinculos_map:
        cursor.execute("INSERT INTO vinculos (nome, login, data_alteracao) VALUES ('CLT', 'sistema', datetime('now'))")
        vinculos_map["CLT"] = cursor.lastrowid
    if "RJU" not in vinculos_map:
        cursor.execute("INSERT INTO vinculos (nome, login, data_alteracao) VALUES ('RJU', 'sistema', datetime('now'))")
        vinculos_map["RJU"] = cursor.lastrowid

    # 5. Mapeamento de Cargos por Nome e Carga Horária
    cursor.execute("SELECT id, UPPER(nome), carga_horaria FROM cargos")
    cargos_rows = cursor.fetchall()
    cargos_map = {}
    for cid, cnome, cch in cargos_rows:
        cargos_map[(cnome, cch)] = cid
        if cnome not in cargos_map:
            cargos_map[cnome] = cid

    def get_or_create_cargo(nome_cargo, ch_cargo):
        nome_c = nome_cargo.strip().upper()
        key = (nome_c, ch_cargo)
        if key in cargos_map:
            return cargos_map[key]
        cursor.execute("""
            INSERT INTO cargos (nome, carga_horaria, login, data_alteracao)
            VALUES (?, ?, 'sistema', datetime('now'))
        """, (nome_c, ch_cargo))
        new_cid = cursor.lastrowid
        cargos_map[key] = new_cid
        cargos_map[nome_c] = new_cid
        return new_cid

    # 6. Mapeamento de Escalas / Códigos
    cursor.execute("SELECT id, UPPER(sigla), codigo FROM escalas")
    escalas_rows = cursor.fetchall()
    escalas_map = {row[1]: row[0] for row in escalas_rows}
    
    escalas_necessarias = {
        "D6": ("07:00:00", "13:00:00", "DIURNO 6H"),
        "M15": ("07:00:00", "13:00:00", "MANHÃ 6H (M15)"),
        "FD0": ("00:00:00", "00:00:00", "FOLGA DIARISTA / FERIADO"),
        "FD6": ("07:00:00", "13:00:00", "FOLGA DIARISTA COMPENSADA"),
        "FE12D": ("07:00:00", "19:00:00", "FÉRIAS DIURNO 12H"),
        "FE6": ("07:00:00", "13:00:00", "FÉRIAS DIURNO 6H"),
        "FE8": ("07:00:00", "16:00:00", "FÉRIAS DIURNO 8H"),
        "AB12D": ("07:00:00", "19:00:00", "ABONO DIURNO 12H"),
        "MT26": ("07:00:00", "13:00:00", "MANHÃ/TARDE 6H")
    }

    for sig, (ini, fim, desc) in escalas_necessarias.items():
        if sig not in escalas_map:
            cursor.execute("""
                INSERT INTO escalas (sigla, codigo, inicio_jornada, fim_jornada, descricao, apenas_assistenciais, login, data_alteracao)
                VALUES (?, ?, ?, ?, ?, 1, 'sistema', datetime('now'))
            """, (sig, sig, ini, fim, desc))
            escalas_map[sig] = cursor.lastrowid

    escala_padrao_id = escalas_map.get("D6") or (list(escalas_map.values())[0] if escalas_map else 1)

    # 7. Inserir/Atualizar Funcionários, Lotações e Grades
    mes_alvo = 4
    ano_alvo = 2026

    for item in TABELA_ONCOLOGIA:
        matricula = item["matricula"].strip()
        nome = item["nome"].strip()
        cargo_nome = item["cargo"].strip().upper()
        vinculo_tipo = item["vinculo"].strip().upper()
        vinculo_id = vinculos_map.get(vinculo_tipo, vinculos_map.get("CLT", 1))
        ch = item["ch"]

        cargo_id = get_or_create_cargo(cargo_nome, ch)

        # 7.1 Localizar funcionário por matrícula ou nome
        cursor.execute("SELECT id FROM funcionarios WHERE matricula = ?", (matricula,))
        func_row = cursor.fetchone()

        if func_row:
            func_id = func_row[0]
            cursor.execute("""
                UPDATE funcionarios 
                SET nome = ?, cargo_id = ?, vinculo_id = ?, escala_id = ?
                WHERE id = ?
            """, (nome, cargo_id, vinculo_id, escala_padrao_id, func_id))
        else:
            cursor.execute("SELECT id FROM funcionarios WHERE UPPER(nome) = ?", (nome.upper(),))
            func_by_nome = cursor.fetchone()
            if func_by_nome:
                func_id = func_by_nome[0]
                cursor.execute("""
                    UPDATE funcionarios 
                    SET matricula = ?, cargo_id = ?, vinculo_id = ?, escala_id = ?
                    WHERE id = ?
                """, (matricula, cargo_id, vinculo_id, escala_padrao_id, func_id))
            else:
                cursor.execute("""
                    INSERT INTO funcionarios (matricula, nome, cargo_id, escala_id, vinculo_id, login, data_alteracao)
                    VALUES (?, ?, ?, ?, ?, 'sistema', datetime('now'))
                """, (matricula, nome, cargo_id, escala_padrao_id, vinculo_id))
                func_id = cursor.lastrowid
                print(f"Funcionário cadastrado: {nome} ({matricula}) - ID {func_id}")

        # 7.2 Garantir Lotação ativa na Oncologia
        cursor.execute("""
            SELECT id FROM funcionarios_lotacoes 
            WHERE funcionario_id = ? AND (uorg_id = ? OR unidade_id = ?)
        """, (func_id, onco_id, onco_id))
        lot_row = cursor.fetchone()
        if not lot_row:
            cursor.execute("""
                INSERT INTO funcionarios_lotacoes (funcionario_id, uorg_id, unidade_id, posto_id, data_inicio, data_fim, login, data_alteracao)
                VALUES (?, ?, ?, ?, '2025-01-01', NULL, 'sistema', datetime('now'))
            """, (func_id, onco_id, onco_id, posto_onco_id))
            print(f"Lotação na Oncologia criada para {nome}")

        # 7.3 Localizar ou Criar Grade do mês 4/2026
        cursor.execute("""
            SELECT id FROM grades 
            WHERE funcionario_id = ? AND uorg_id = ? AND mes = ? AND ano = ?
        """, (func_id, onco_id, mes_alvo, ano_alvo))
        grade_row = cursor.fetchone()

        if grade_row:
            grade_id = grade_row[0]
            cursor.execute("DELETE FROM grade_dias WHERE grade_id = ?", (grade_id,))
        else:
            cursor.execute("""
                INSERT INTO grades (funcionario_id, uorg_id, posto_id, mes, ano, status, observacao, login, data_alteracao)
                VALUES (?, ?, ?, ?, ?, 'Rascunho', 'Escala importada da Oncologia (Ambulatório)', 'sistema', datetime('now'))
            """, (func_id, onco_id, posto_onco_id, mes_alvo, ano_alvo))
            grade_id = cursor.lastrowid

        # 7.4 Inserir os dias da escala de Abril (1 a 30)
        dias_dict = item["dias"]
        for dia_num in range(1, 31):
            sigla = dias_dict.get(dia_num)
            if sigla:
                escala_id = escalas_map.get(sigla.upper())
                cursor.execute("""
                    INSERT INTO grade_dias (grade_id, dia, escala_id, legenda_sigla)
                    VALUES (?, ?, ?, ?)
                """, (grade_id, dia_num, escala_id, sigla))

    print(f"Carga da Oncologia para Abril/{ano_alvo} concluída com sucesso para {len(TABELA_ONCOLOGIA)} colaboradores!")
