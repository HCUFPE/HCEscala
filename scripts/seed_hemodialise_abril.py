def seed_hemodialise_sync(cursor):
    """
    Executa o seed síncrono do Posto Hemodiálise e escala de Abril de 2026.
    """
    # 1. Obter ou criar a UORG Unidade de Sistema Urinário
    cursor.execute("SELECT id, nome FROM uorgs WHERE UPPER(nome) LIKE '%SISTEMA URINARIO%' OR UPPER(nome) LIKE '%SISTEMA URINÁRIO%'")
    uorg_row = cursor.fetchone()
    if not uorg_row:
        cursor.execute("INSERT INTO uorgs (nome, sigla, login, data_alteracao) VALUES ('UNIDADE DE SISTEMA URINÁRIO', 'USU', 'sistema', datetime('now'))")
        uorg_id = cursor.lastrowid
    else:
        uorg_id = uorg_row[0]

    # 2. Obter ou criar Posto de Serviço Hemodiálise ligado à Unidade de Sistema Urinário
    cursor.execute("SELECT id, nome FROM postos WHERE UPPER(nome) LIKE '%HEMODI%' AND (uorg_id = ? OR unidade_id = ?)", (uorg_id, uorg_id))
    posto_row = cursor.fetchone()
    if not posto_row:
        cursor.execute("SELECT id, nome FROM postos WHERE UPPER(nome) LIKE '%HEMODI%'")
        posto_any_row = cursor.fetchone()
        if posto_any_row:
            posto_id = posto_any_row[0]
            cursor.execute("UPDATE postos SET uorg_id = ?, unidade_id = ?, data_alteracao = datetime('now') WHERE id = ?", (uorg_id, uorg_id, posto_id))
        else:
            cursor.execute("INSERT INTO postos (nome, uorg_id, unidade_id, login, data_alteracao) VALUES ('HEMODIÁLISE', ?, ?, 'sistema', datetime('now'))", (uorg_id, uorg_id))
            posto_id = cursor.lastrowid
    else:
        posto_id = posto_row[0]

    # 3. Garantir escalas utilizadas
    escalas_para_criar = [
        ("FE12D", "FÉRIAS 12H DIURNO", "FE12D", "07:00", "19:00", 0),
        ("CH12D", "COMPENSAÇÃO DE HORAS 12H DIURNO", "CH12D", "07:00", "19:00", 0),
        ("AFIN6", "AFINIDADE 6H", "AFIN6", "07:00", "13:00", 1),
        ("AFIN7", "AFINIDADE 7H", "AFIN7", "07:00", "14:00", 1),
        ("AFIN8", "AFINIDADE 8H", "AFIN8", "07:00", "15:00", 1),
    ]
    for sigla, desc, cod, ini, fim, assist in escalas_para_criar:
        cursor.execute("SELECT id FROM escalas WHERE UPPER(sigla) = ?", (sigla.upper(),))
        if not cursor.fetchone():
            cursor.execute("""
                INSERT INTO escalas (sigla, descricao, codigo, inicio_jornada, fim_jornada, apenas_assistenciais, login, data_alteracao)
                VALUES (?, ?, ?, ?, ?, ?, 'sistema', datetime('now'))
            """, (sigla.upper(), desc, cod, ini, fim, assist))

    # Cache de escalas
    cursor.execute("SELECT UPPER(sigla), id FROM escalas")
    escalas_map = {r[0].strip(): r[1] for r in cursor.fetchall()}
    escala_d6_id = escalas_map.get("D6", 1)

    # Cache de cargos e vínculos
    cursor.execute("SELECT id, UPPER(nome) FROM cargos")
    cargos_map = {r[1]: r[0] for r in cursor.fetchall()}
    cargo_tec_enf_id = None
    for c_nome, c_id in cargos_map.items():
        if "TEC" in c_nome and "ENF" in c_nome:
            cargo_tec_enf_id = c_id
            break
    if not cargo_tec_enf_id:
        cargo_tec_enf_id = 1

    cursor.execute("SELECT id, UPPER(nome) FROM vinculos")
    vinculos_map = {r[1]: r[0] for r in cursor.fetchall()}
    vinculo_ebserh_id = vinculos_map.get("EBSERH", 1)
    vinculo_rju_id = vinculos_map.get("RJU", 1)

    mes_alvo = 4
    ano_alvo = 2026
    total_processados = 0

    for item in TABELA_HEMODIALISE:
        mat = item["matricula"].strip()
        nome = item["nome"].strip()
        vinculo_nome = item["vinculo"].strip().upper()
        v_id = vinculo_rju_id if "RJU" in vinculo_nome else vinculo_ebserh_id

        # 3.1 Localizar ou Cadastrar Funcionário
        cursor.execute("SELECT id, nome FROM funcionarios WHERE matricula = ?", (mat,))
        func_row = cursor.fetchone()
        if not func_row:
            cursor.execute("SELECT id, matricula FROM funcionarios WHERE UPPER(TRIM(nome)) = ?", (nome.upper(),))
            func_row = cursor.fetchone()

        if not func_row:
            cursor.execute("""
                INSERT INTO funcionarios (matricula, nome, cargo_id, escala_id, vinculo_id, login, data_alteracao)
                VALUES (?, ?, ?, ?, ?, 'sistema', datetime('now'))
            """, (mat, nome, cargo_tec_enf_id, escala_d6_id, v_id))
            func_id = cursor.lastrowid
        else:
            func_id = func_row[0]
            cursor.execute("UPDATE funcionarios SET matricula = ?, nome = ?, data_alteracao = datetime('now') WHERE id = ?", (mat, nome, func_id))

        # 3.2 Garantir Lotação no Posto Hemodiálise da Unidade de Sistema Urinário
        cursor.execute("""
            SELECT id FROM funcionarios_lotacoes 
            WHERE funcionario_id = ? AND uorg_id = ? AND (data_fim IS NULL OR data_fim = '' OR data_fim >= '2026-04-01')
        """, (func_id, uorg_id))
        lot_row = cursor.fetchone()
        if not lot_row:
            cursor.execute("""
                INSERT INTO funcionarios_lotacoes (funcionario_id, uorg_id, unidade_id, posto_id, data_inicio, data_fim, login, data_alteracao)
                VALUES (?, ?, ?, ?, '2025-01-01', NULL, 'sistema', datetime('now'))
            """, (func_id, uorg_id, uorg_id, posto_id))
        else:
            lot_id = lot_row[0]
            cursor.execute("UPDATE funcionarios_lotacoes SET posto_id = ?, data_alteracao = datetime('now') WHERE id = ?", (posto_id, lot_id))

        # 3.3 Inserir ou Atualizar Grade de Abril de 2026 (mes=4, ano=2026)
        cursor.execute("""
            SELECT id FROM grades 
            WHERE funcionario_id = ? AND uorg_id = ? AND mes = ? AND ano = ?
        """, (func_id, uorg_id, mes_alvo, ano_alvo))
        grade_row = cursor.fetchone()
        if grade_row:
            grade_id = grade_row[0]
            cursor.execute("UPDATE grades SET posto_id = ?, observacao = 'Escala Hemodiálise Abril/2026', data_alteracao = datetime('now') WHERE id = ?", (posto_id, grade_id))
            cursor.execute("DELETE FROM grade_dias WHERE grade_id = ?", (grade_id,))
        else:
            cursor.execute("""
                INSERT INTO grades (funcionario_id, uorg_id, posto_id, mes, ano, status, observacao, login, data_alteracao)
                VALUES (?, ?, ?, ?, ?, 'Rascunho', 'Escala Hemodiálise Abril/2026', 'sistema', datetime('now'))
            """, (func_id, uorg_id, posto_id, mes_alvo, ano_alvo))
            grade_id = cursor.lastrowid

        # 3.4 Inserir os dias da escala do colaborador
        for dia_num, sigla in item["dias"].items():
            sigla_clean = sigla.strip().upper()
            e_id = escalas_map.get(sigla_clean)
            cursor.execute("""
                INSERT INTO grade_dias (grade_id, dia, escala_id, legenda_sigla)
                VALUES (?, ?, ?, ?)
            """, (grade_id, dia_num, e_id, sigla_clean))

        total_processados += 1

    print(f"Carga de Hemodiálise concluída: {total_processados} colaboradores importados na UORG ID {uorg_id} e Posto ID {posto_id}.")
    return {"status": "success", "total_processados": total_processados, "uorg_id": uorg_id, "posto_id": posto_id}
